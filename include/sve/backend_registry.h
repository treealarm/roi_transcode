#pragma once

// Which backends this deployment actually has -- TZ v4.2 §26.4.
//
// Until 4.2 the answer was a switch in one translation unit naming every backend by its
// factory function, which meant the core could not be built without all of them. §5.5 makes
// each backend an independent optional component and §26.4 says how one arrives:
//
//     Static registration выполняется явно и не должна зависеть только от global
//     constructors или linker-specific --whole-archive
//
// So registration is a call, not a side effect. Each component exports one function that
// hands its backend to a registry; the deployment calls the ones it linked. That rules out
// the two shortcuts on purpose: a global constructor in a static library is dropped unless
// the consumer passes --whole-archive, which pushes a build condition onto whoever embeds
// us -- and ta_vms embeds us with add_subdirectory().
//
// §26.4 also asks that static and dynamic delivery share one SveBackendPluginDescriptorV1,
// and since 2026-09-01 they do: sve/backend_plugin.h carries the descriptor, this registry
// is the only thing that reads one, and a component describes itself once for both paths.
// The dynamic loader that finds a descriptor in a shared module is a later slice; what it
// finds is already defined, and already the thing the static path registers.

#include "sve/backend_plugin.h"
#include "sve/backend_selection.h"
#include "sve/status.h"

#include <vector>

namespace sve {

class IEncoderBackend;

/// The backends available to this process, by the identifier §8.2 gives them.
///
/// Holds references, not ownership: a backend is a stateless immortal singleton (Р7), and
/// a registry that owned them would be inventing a lifetime none of them has.
class BackendRegistry {
public:
    /// Adds the backend `descriptor` describes, under the identifier it declares.
    ///
    /// This is the only way in, and it takes a descriptor rather than a backend so that
    /// there is one route for both of §26.4's delivery paths. Everything the descriptor
    /// claims is checked before anything is registered: `abi_version` and `descriptor_size`
    /// against this build's, a non-null `acquire` that yields a non-null backend, and the
    /// backend's own `kind()` against the declared identifier -- a component that says
    /// X264Direct and hands over something else would otherwise be registered under a name
    /// answering with another backend's capabilities.
    ///
    /// A second registration of the same identifier is `InvalidArgument`, including when
    /// one comes from a static component and the other from a plugin. §26.4 forbids silent
    /// override in as many words, and it is the right refusal: two implementations
    /// answering to one name differ somewhere, and whichever won would be a coin toss made
    /// at link time.
    Status Register(const SveBackendPluginDescriptorV1& descriptor) noexcept;

    /// Null when this build does not have it, which is a normal answer rather than an
    /// error -- §26.4 requires that removing a component leaves the core standing.
    const IEncoderBackend* Find(Backend kind) const noexcept;

    /// Everything registered, in registration order. Used to honour `allow_unlisted` and
    /// by the capability report of §23.
    std::vector<Backend> kinds() const;

private:
    std::vector<const IEncoderBackend*> m_backends;
};

/// One per component, and only the ones this build has are defined. §26.4 names them.
Status RegisterX264Backend(BackendRegistry& registry) noexcept;
Status RegisterX265Backend(BackendRegistry& registry) noexcept;
Status RegisterOneVplBackend(BackendRegistry& registry) noexcept;
Status RegisterFfmpegBackends(BackendRegistry& registry) noexcept;

/// Generated by the build from the components that were enabled, so the core never names a
/// backend that is not there. This is the aggregator §26.4 allows a deployment to provide.
Status RegisterDeploymentBackends(BackendRegistry& registry) noexcept;

/// The registry the library's own entry points use, filled by RegisterDeploymentBackends
/// on first use. An application assembling its own may build a BackendRegistry instead;
/// this one exists so that the common case needs no assembly at all.
BackendRegistry& default_backend_registry();

} // namespace sve
