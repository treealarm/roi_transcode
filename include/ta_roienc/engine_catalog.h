#pragma once

// Which backends this deployment actually has.
//
// Each backend is an independent optional component, so the core cannot name them all.
// Registration is a call, not a side effect: each component exports one function that hands
// its backend to a registry, and the deployment calls the ones it linked. That rules out a
// global constructor on purpose: in a static library one is dropped unless the consumer
// passes --whole-archive, which pushes a build condition onto whoever embeds us with
// add_subdirectory().
//
#include "ta_roienc/engine_order.h"
#include "ta_roienc/verdict.h"

#include <vector>

namespace ta_roienc {

class IEngine;

/// The backends available to this process, by their Engine identifier.
///
/// Holds references, not ownership: a backend is a stateless immortal singleton, and a
/// registry that owned them would be inventing a lifetime none of them has.
class EngineCatalog {
public:
    /// Adds `backend` under the identifier its own `kind()` reports.
    ///
    /// A second registration of the same identifier is `InvalidArgument`: two
    /// implementations answering to one name differ somewhere, and whichever won would be a
    /// coin toss made at link time.
    Verdict Register(const IEngine& backend) noexcept;

    /// Null when this build does not have it, which is a normal answer rather than an
    /// error -- removing a component must leave the core standing.
    const IEngine* Find(Engine kind) const noexcept;

    /// Everything registered, in registration order. Used to honour `allow_unlisted`.
    std::vector<Engine> kinds() const;

private:
    std::vector<const IEngine*> m_backends;
};

/// One per component, and only the ones this build has are defined.
Verdict RegisterX264Engine(EngineCatalog& registry) noexcept;
Verdict RegisterX265Engine(EngineCatalog& registry) noexcept;
Verdict RegisterOneVplEngine(EngineCatalog& registry) noexcept;
Verdict RegisterFfmpegEngines(EngineCatalog& registry) noexcept;

/// Generated by the build from the components that were enabled, so the core never names a
/// backend that is not there.
Verdict RegisterDeploymentEngines(EngineCatalog& registry) noexcept;

/// The registry the library's own entry points use, filled by RegisterDeploymentEngines
/// on first use. An application assembling its own may build a EngineCatalog instead;
/// this one exists so that the common case needs no assembly at all.
EngineCatalog& default_engine_catalog();

} // namespace ta_roienc
